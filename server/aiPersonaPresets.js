/**
 * 将旧房间中保存的任意历史版本官方预设（含 600 字截断版、旧版蓝发小女仆等）自动升级为最新预设文本；
 * 房主自己手写的自定义角色设定原样保留。
 */
export function upgradeLegacyRoomAiPersona(value) {
  const normalized = String(value || '')
    .replace(/\r\n/g, '\n')
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '')
    .trim();
  if (!normalized) return '';
  const mappedId = LEGACY_PRESET_ID_BY_VALUE.get(normalized);
  if (mappedId && PRESET_BY_ID.has(mappedId)) {
    return PRESET_BY_ID.get(mappedId);
  }
  return normalized;
}

export function isRoomAiPersonaAllowed(value) {
  const upgraded = upgradeLegacyRoomAiPersona(value);
  return upgraded.length <= MAX_CUSTOM_ROOM_AI_PERSONA_LENGTH
    || AI_PERSONA_PRESETS.some((preset) => preset.value === upgraded);
}
